async def seed_content(db):
    from datetime import datetime, timezone
    now = datetime.now(timezone.utc)
    if await db.services.count_documents({}) == 0:
        for s in SERVICES:
            s.setdefault("seo", {"title": s["title"], "description": s["short"]})
            s["created_at"] = s["updated_at"] = now
        await db.services.insert_many([dict(s) for s in SERVICES])
    if await db.projects.count_documents({}) == 0:
        for p in PROJECTS:
            p["created_at"] = p["updated_at"] = now
        await db.projects.insert_many([dict(p) for p in PROJECTS])
    if await db.packages.count_documents({}) == 0:
        for pk in PACKAGES:
            pk["created_at"] = pk["updated_at"] = now
        await db.packages.insert_many([dict(pk) for pk in PACKAGES])
    if await db.settings.count_documents({"key": "site"}) == 0:
        doc = dict(SETTINGS)
        doc["updated_at"] = now
        await db.settings.insert_one(doc)
